import type { BrowserWindowConstructorOptions } from "electron";

/** Height of the window's integrated title bar; apps/window/src/style.css draws its row at the same height. */
export const TITLEBAR_HEIGHT = 40;
const MACOS_WINDOW_BUTTON_RADIUS = 7;
const TITLEBAR_COLOR = "#01000000"; // #00000000 does not work correctly on Linux
const TITLEBAR_LIGHT_SYMBOL_COLOR = "#1f2937";
const TITLEBAR_DARK_SYMBOL_COLOR = "#f8fafc";

export type WindowTitleBarOptions = Pick<
  BrowserWindowConstructorOptions,
  "titleBarOverlay" | "titleBarStyle" | "trafficLightPosition"
>;

/** macOS keeps its traffic lights inset in the title bar; Windows draws its caption buttons over it. */
export function windowTitleBarOptions(
  shouldUseDarkColors: boolean,
  platform: NodeJS.Platform,
): WindowTitleBarOptions {
  if (platform === "darwin") {
    return {
      titleBarStyle: "hiddenInset",
      trafficLightPosition: { x: 16, y: TITLEBAR_HEIGHT / 2 - MACOS_WINDOW_BUTTON_RADIUS },
    };
  }
  return {
    titleBarStyle: "hidden",
    titleBarOverlay: {
      color: TITLEBAR_COLOR,
      height: TITLEBAR_HEIGHT,
      symbolColor: shouldUseDarkColors ? TITLEBAR_DARK_SYMBOL_COLOR : TITLEBAR_LIGHT_SYMBOL_COLOR,
    },
  };
}
